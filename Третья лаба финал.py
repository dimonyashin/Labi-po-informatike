x = float(input("Введите значение x (|x| < 1): ")) # Ввод значения x (для сходимости ряда должно быть |x| < 1)
eps = 0.0001

summa = 0.0
i = 1

# Вычисляем первый член ряда
a = (- (x ** i) * (i + 1)) / ((i + 2) * i)

# Цикл продолжается, пока текущий член ряда по модулю больше или равен eps
while abs(a) >= eps:
    summa += a  # Прибавляем член ряда к общей сумме
    i += 1            # Переходим к следующему шагу
    a = (- (x ** i) * (i + 1)) / ((i + 2) * i)  # Считаем новый член ряда

result = round(summa, 6) # Округляем результат до шести знаков
print(f"Результат вычисления суммы: {result}")
print(f"Количество учтенных членов ряда: {i - 1}")
