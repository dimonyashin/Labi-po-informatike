L = 0 # начльное значение длины выработки
N = int(input("Введите число смен ")) 
P = float(input("Введите число метров, которое комбайн проходит за смену ")) 
i=1 # номер текущей смены
while i <= N : # цикл выполняется, пока номер текущей смены не превысит общее количество смен
    L += P # увеличиваем длину выработки на количество метров, пройденных комбайном за смену
    result = round(L, 2) # округляем результат до двух знаков после запятой
    print(f"Общая длина выработки после {i} смен: {result}") # выводим номер текущей смены и общую длину выработки 
    i += 1 # увеличиваем номер текущей смены на 1
    