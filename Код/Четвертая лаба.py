def largest_load(values): # создаем функцию
    max_load = values[0] # принимаем первый член за максимум
    for value in values[1:]: # цикл for проходится по всем элементам списка, начиная со второго
        if value > max_load: # если элемент больше максимального, то он становится новым максимом
            max_load = value
            
    return max_load # после завершения цикла функция возращает найденное максимальное значение

test_list = [17, 22, 20, 19] # проверочный список
result = largest_load(test_list) # находим наибольший элемент

print(f"Наибольшая масса груза: {result}") # выводим результат