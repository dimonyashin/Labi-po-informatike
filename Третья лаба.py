A = -6.0    # задаем диапазон значений аргумента х и шаг его изменения      
B = 6.0                     
h = 1.0

print(f"{'Аргумент (x)'} | {'Функция F(x) = |x^3|'}") # выводим заголовок таблицы

x = A # присваиваем переменной x начльное значение диапазона

while x <= B : # выполняем цикл, пока значение х не превысит верхнюю границу диапазона
    
    F_x = abs(x ** 3) # вычисляем значние функции для текущего значния аргумента
    
    print(f"{x}         | {F_x}") # выводим в строчку значение аргумунета и значение функции
    
    x += h # увеличиваем значение аргумента на шаг h